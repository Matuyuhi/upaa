test "known and unknown key codes" {
    try std.testing.expectEqual(@as(vt.GhosttyKey, vt.GHOSTTY_KEY_A), fromMacKeyCode(0));
    try std.testing.expectEqual(@as(vt.GhosttyKey, vt.GHOSTTY_KEY_ARROW_UP), fromMacKeyCode(126));
    try std.testing.expectEqual(@as(vt.GhosttyKey, vt.GHOSTTY_KEY_UNIDENTIFIED), fromMacKeyCode(500));
}
